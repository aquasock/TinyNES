"""Write the preset palettes of FCEUmm's libretro driver (its palettes[] table
in src/drivers/libretro/libretro.c, GPL-2.0, fetched by tools/fetch_fceumm.sh)
as a C header for nes_bench: 64 RGB triples per palette, in the order the
FCEUmm core's FCEUI_SetPaletteArray() takes them.

The header is built into build/ beside the program and never committed, as the
core's own sources are not.  Index 0 is FCEUmm's built-in palette, which needs
no table; 1 to 23 are the presets in upstream's order.  That numbering is the
settings byte TinyTang's /nes.ini parser sends (ports/bl616/tang_nes_ini.c), so
the script fails if the upstream table does not hold exactly these names in
this order, rather than letting the two sides drift apart."""
import argparse
import re
import sys

# The ABI: the /nes.ini value for each settings byte, index 0 first.  The
# preset names are upstream's own core-option values (fceumm_palette).
NAMES = [
    "fceumm",
    "asqrealc", "restored-wii-vc", "wii-vc", "rgb", "yuv-v3",
    "unsaturated-final", "sony-cxa2025as-us", "pal", "bmf-final2",
    "bmf-final3", "smooth-fbx", "composite-direct-fbx", "pvm-style-d93-fbx",
    "ntsc-hardware-fbx", "nes-classic-fbx-fs", "nescap", "wavebeam",
    "digital-prime-fbx", "magnum-fbx", "smooth-v2-fbx", "nes-classic-fbx",
    "royaltea", "mugicha",
]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("libretro_c", help="FCEUmm's src/drivers/libretro/libretro.c")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    text = open(args.libretro_c, encoding="utf-8").read()
    start = text.index("struct st_palettes palettes[] = {")
    end = text.index("};", start)
    entries = re.findall(r'\{\s*"([^"]+)",\s*"([^"]*)",\s*\{([^{}]*)\}\s*\}',
                         text[start:end])
    names = [e[0] for e in entries]
    if names != NAMES[1:]:
        sys.exit(f"{args.libretro_c}: preset names {names} are not the ABI's "
                 f"{NAMES[1:]}; change both sides together")
    tables = []
    for name, _, body in entries:
        values = [int(v, 16) for v in re.findall(r"0[xX]([0-9A-Fa-f]{6})", body)]
        if len(values) != 64:
            sys.exit(f"{args.libretro_c}: {name} has {len(values)} colours, not 64")
        tables.append((name, values))

    with open(args.output, "w", encoding="ascii") as out:
        out.write("// Generated by tools/gen_fceumm_palettes.py from FCEUmm's\n"
                  "// src/drivers/libretro/libretro.c (GPL-2.0, tools/fetch_fceumm.sh).\n"
                  "// Not committed: it stays in build/ with the program.\n"
                  "#pragma once\n#include <stdint.h>\n\n")
        out.write(f"#define NES_PALETTE_COUNT {len(NAMES)}\n\n")
        out.write("static const char *const nes_palette_name[NES_PALETTE_COUNT] = {\n")
        for name in NAMES:
            out.write(f'\t"{name}",\n')
        out.write("};\n\n")
        out.write("// Index 0, FCEUmm's own palette, has no table: entry i here is "
                  "palette i + 1.\n")
        out.write(f"static const uint8_t nes_palette_rgb[{len(tables)}][64 * 3] = {{\n")
        for name, values in tables:
            out.write(f"\t{{ // {name}\n")
            for i in range(0, 64, 8):
                row = ", ".join(f"0x{v >> 16 & 255:02x}, 0x{v >> 8 & 255:02x}, "
                                f"0x{v & 255:02x}" for v in values[i:i + 8])
                out.write(f"\t\t{row},\n")
            out.write("\t},\n")
        out.write("};\n")


if __name__ == "__main__":
    main()
